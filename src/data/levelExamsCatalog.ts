function buildCatalog(): LevelExamItem[] {
  const result: LevelExamItem[] = [];
  const levels = Object.keys(BLUEPRINTS) as Exclude<ExamLevelFilterId, 'all'>[];

  for (const session of EXAM_SESSIONS) {
    for (const lvlId of levels) {
      const groups = BLUEPRINTS[lvlId];
      for (const group of groups) {
        group.subjects.forEach((subj, idx) => {
          const yearSuffix = session.id === '25/26' ? '26' : session.id.slice(-2);
          result.push({
            id: `onefd-${session.id}-${lvlId}-${subj.codeBase}-${idx}`,
            sessionId: session.id,
            sessionTitle: session.label,
            levelId: lvlId,
            levelLabel: group.levelLabel,
            streamLabel: group.streamLabel,
            subject: subj.subject,
            duration: subj.duration,
            code: `${subj.codeBase}-${yearSuffix}`,
            pagesCount: 2,
            summary: `${subj.summary} — موضوع ${session.shortLabel}`,
            sections: subj.sections,
            solutionSections: subj.solutionSections,
          });
        });
      }
    }
  }

  return result;
}

export const LEVEL_EXAMS_CATALOG: LevelExamItem[] = buildCatalog();

